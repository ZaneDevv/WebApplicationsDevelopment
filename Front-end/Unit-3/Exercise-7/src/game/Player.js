class Player
{
    // -----------------------------------------
    // ATTRIBUTES
    // -----------------------------------------

    #name = "";
    #cards = [];

    // -----------------------------------------
    // CONSTRUCTORS
    // -----------------------------------------

    constructor(name)
    {
        this.#name = name;
    }

    // -----------------------------------------
    // METHODS
    // -----------------------------------------

    getCard(card)
    {
        this.#cards.push(card);
    }
}